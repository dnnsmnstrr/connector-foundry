// Bundles every .scad source the browser needs (lib + parts +
// assemblies, and whatever they include from the vendored upstreams —
// see ROOT_DIRS) into one JSON blob, and writes
// catalogue.yaml alongside it as catalogue.json (parsed here, once, so
// the browser needs no YAML parser), so the app can fetch its whole
// virtual filesystem in one request instead of one per file. Run before
// dev/build (see package.json), and re-run live by
// vite-plugin-scad-watch.mjs while `npm run dev` is up.
//
// Each part's gallery render (docs/img/, made by `foundry preview`) is
// copied into public/thumbnails/ for the command palette's part rows,
// and the part's entry in catalogue.json gets a `thumbnail` path — a
// field the build derives, not one catalogue.yaml has, so the CLI and the
// catalogue schema never see it. A part with no render has no field and
// shows its system's initial instead.
//
// Bundle shape: { files: { "lib/x.scad": "<source>" }, assets: {
// "parts/deckmate/universal_grip.stl": "<base64>" } } — `files` is
// every .scad as text, `assets` every binary a part import()s, mounted
// at the same relative paths by openscad-worker.js so a relative
// import() resolves identically in the browser and on disk.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
export const REPO_ROOT = path.resolve(__dirname, "..", "..");
export const WEB_PUBLIC = path.resolve(__dirname, "..", "public");
export const GALLERY_DIR = path.join(REPO_ROOT, "docs", "img");
export const THUMBNAIL_DIR = path.join(WEB_PUBLIC, "thumbnails");

// The repo's own sources are the roots: every .scad under these is
// bundled, plus every file reachable from them through `include <..>`
// / `use <..>` (transitively — BOSL2's std.scad alone pulls in ~30
// siblings). Vendored upstreams come in only through that closure, so
// an upstream's examples, tests, customizers and unrelated subsystems
// (QuackWorks is a large repo of mostly unrelated systems; technic.scad
// ships gears and examples beside its one library file) never reach
// the browser. Binary assets a part import()s (.stl) are taken from
// the root directories only — an upstream's sample STLs are not
// something any part here reaches for, and they would dwarf the sources.
export const ROOT_DIRS = ["lib", "parts", "assemblies"];

// Everything a change can affect, for the dev watcher
// (vite-plugin-scad-watch.mjs): the roots, and the vendor tree the
// closure may reach into.
export const SOURCE_DIRS = [...ROOT_DIRS, "vendor"];

// `include <x>` / `use <x>`, with the target. A leading `./`, `../` or
// `/` makes it a path (resolved against the including file's directory);
// anything else is a library-style name, which OpenSCAD resolves next to
// the including file first and then via OPENSCADPATH.
const INCLUDE = /^\s*(?:include|use)\s*<([^>]+)>/gm;

// Upstreams written for OpenSCAD's library folder ask for their
// dependencies by library name — `include <BOSL2/std.scad>` — which
// resolves via OPENSCADPATH on a real install. There is no OPENSCADPATH
// in the WASM build, so those includes would simply not resolve.
// OpenSCAD does look next to the including file first, so a one-line
// redirect placed there is enough, and costs a few dozen bytes instead
// of a second copy of BOSL2.
const SHIM_HEADER =
  `// Generated by sync-scad.mjs: forwards a library-path include to\n` +
  `// the vendored copy, since the WASM build has no OPENSCADPATH.\n`;

// Binary files a part may import() — shipped only from this repo's own
// directories, never from vendor/.
const ASSET_EXTENSIONS = new Set([".stl"]);

function isAsset(file) {
  return ASSET_EXTENSIONS.has(path.extname(file).toLowerCase());
}

function isVendored(relPath) {
  return relPath.split("/")[0] === "vendor";
}

// Whether a change to `file` (absolute) can affect the bundle, for the
// dev watcher. Any .scad may be in the closure; assets only from the
// roots.
export function isBundledFile(file) {
  if (file.endsWith(".scad")) return true;
  const rel = toRel(file);
  return isAsset(file) && !isVendored(rel);
}

function toRel(file) {
  return path.relative(REPO_ROOT, file).split(path.sep).join("/");
}

function toAbs(rel) {
  return path.join(REPO_ROOT, ...rel.split("/"));
}

function walk(dir, out) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (isBundledFile(full)) out.push(full);
  }
}

function libraryRoots() {
  return new Set(
    fs
      .readdirSync(path.join(REPO_ROOT, "vendor"), { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name),
  );
}

// A commented-out include is still text the regex would match; drop
// comments first so a dead `// include <old.scad>` doesn't pull a file
// in (or warn about one that no longer exists).
function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
}

// Every include/use target of `rel`'s source, resolved to a repo-relative
// path: [{ target, resolved, shim }] where `shim` is the repo-relative
// path of a forwarding stub to generate when a library-style name was
// satisfied from vendor/ rather than next to the including file.
function resolveIncludes(rel, source, roots) {
  const dir = path.posix.dirname(rel);
  const found = [];
  for (const match of stripComments(source).matchAll(INCLUDE)) {
    const target = match[1].trim();
    if (target.startsWith("/")) continue; // absolute: nothing we could bundle
    const sibling = path.posix.normalize(path.posix.join(dir, target));
    const isPath = target.startsWith("./") || target.startsWith("../");
    if (isPath || fs.existsSync(toAbs(sibling))) {
      found.push({ target, resolved: sibling });
      continue;
    }
    // Library-style name not found next to the file: vendor/<Lib>/..
    const lib = target.split("/")[0];
    if (roots.has(lib)) found.push({ target, resolved: path.posix.join("vendor", target), shim: sibling });
    // Anything else (MCAD and the other built-in libraries) is left to
    // the WASM build, which has the same libraries a native OpenSCAD has.
  }
  return found;
}

// Reads the roots and follows includes until nothing new is reached.
// Returns { files, assets } keyed by repo-relative path.
function collect() {
  const files = {};
  const assets = {};
  const roots = libraryRoots();
  const queue = [];
  const missing = new Set();

  for (const dir of ROOT_DIRS) {
    const found = [];
    walk(path.join(REPO_ROOT, dir), found);
    for (const file of found) {
      const rel = toRel(file);
      if (isAsset(file)) assets[rel] = fs.readFileSync(file).toString("base64");
      else queue.push(rel);
    }
  }

  while (queue.length) {
    const rel = queue.shift();
    if (files[rel] !== undefined) continue;
    const abs = toAbs(rel);
    if (!fs.existsSync(abs)) {
      missing.add(rel);
      continue;
    }
    const source = fs.readFileSync(abs, "utf8");
    files[rel] = source;
    for (const { resolved, shim } of resolveIncludes(rel, source, roots)) {
      if (shim && files[shim] === undefined) {
        const hop = path.posix.relative(path.posix.dirname(shim), resolved);
        files[shim] = `${SHIM_HEADER}include <${hop}>\n`;
      }
      queue.push(resolved);
    }
  }

  return { files, assets, missing: [...missing] };
}

// A missing vendor file is almost always a submodule that was never
// checked out. A bundle without it still loads, but every part that
// includes from it fails in the browser with an unhelpful "can't open
// include" — so say what's missing here, at the one point that can tell.
function describeMissing(missing) {
  return missing.map(
    (rel) =>
      `  ${rel} is included but does not exist` +
      (isVendored(rel) ? " (vendored: submodule not checked out?)" : ""),
  );
}

export class MissingIncludeError extends Error {}

// Top-level `NAME = <simple literal>;` assignments in lib/constants.scad
// — the browser's copy of catalogue defaults for the "same override
// layer" global settings (FIT_CLEARANCE etc.), so the UI has a real
// catalogue-default number to diff/reset against instead of a
// hand-duplicated one. Only plain number/bool/quoted-string literals
// are picked up (the vast majority of constants.scad); a computed
// expression is skipped rather than guessed at, same spirit as
// cli/foundry.py's constants_names() only checking the name exists —
// this is that plus the value, best-effort.
const GLOBAL_CONST = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^;]+);/gm;

function parseSimpleLiteral(raw) {
  const trimmed = raw.trim();
  if (trimmed === "true") return true;
  if (trimmed === "false") return false;
  if (/^-?\d+(\.\d+)?$/.test(trimmed)) return Number(trimmed);
  if (/^"[^"]*"$/.test(trimmed)) return JSON.parse(trimmed);
  return undefined; // computed expression — not a catalogue default we can show
}

function globalConstants() {
  const source = fs.readFileSync(path.join(REPO_ROOT, "lib", "constants.scad"), "utf8");
  const values = {};
  for (const match of source.matchAll(GLOBAL_CONST)) {
    const value = parseSimpleLiteral(match[2]);
    if (value !== undefined) values[match[1]] = value;
  }
  return values;
}

// catalogue.yaml as the plain object the browser fetches. Parsed here
// rather than in the page so js-yaml stays out of the main bundle; the
// shape check lives in useCatalogue.js, which names the file in its
// error either way.
function catalogue() {
  return yaml.load(fs.readFileSync(path.join(REPO_ROOT, "catalogue.yaml"), "utf8"));
}

// A part's gallery image's file name — its id with "/" as "_", the same
// slug cli/foundry.py's slug() and catalogueUtils.js's slugify() make —
// or null for an id that would not make a plain file name.
/** @param {string} partId */
export function thumbnailName(partId) {
  const slug = String(partId).replace(/\//g, "_");
  return /^[A-Za-z0-9_-]+$/.test(slug) ? `${slug}.png` : null;
}

// Copies each part's gallery image, when it has one, into `thumbnailDir`
// (only when the bytes differ, so a dev server's watcher sees no change
// for nothing), removes images no part has any more, and sets each copied
// part's `thumbnail`. Returns how many there are.
export function syncThumbnails(parts, { galleryDir = GALLERY_DIR, thumbnailDir = THUMBNAIL_DIR } = {}) {
  fs.mkdirSync(thumbnailDir, { recursive: true });
  const kept = new Set();
  for (const part of parts) {
    const name = thumbnailName(part.id);
    const from = name && path.join(galleryDir, name);
    if (!from || !fs.existsSync(from)) continue;
    const to = path.join(thumbnailDir, name);
    const bytes = fs.readFileSync(from);
    if (!fs.existsSync(to) || !fs.readFileSync(to).equals(bytes)) fs.writeFileSync(to, bytes);
    part.thumbnail = `thumbnails/${name}`;
    kept.add(name);
  }
  for (const file of fs.readdirSync(thumbnailDir)) {
    if (!kept.has(file)) fs.rmSync(path.join(thumbnailDir, file));
  }
  return kept.size;
}

// Returns the { files, assets, thumbnails } counts. See the header for the bundle shape.
//
// `strict` (what `npm run sync-scad`, and so every dev/build, uses)
// throws MissingIncludeError before writing anything when an include
// does not resolve: a build would otherwise ship parts that cannot
// render. The dev watcher calls this non-strict — a half-saved file
// mid-edit must not take the dev server down — and only gets a warning.
export function syncScad({ strict = false } = {}) {
  const { files, assets, missing } = collect();
  if (missing.length) {
    const lines = describeMissing(missing);
    if (strict) throw new MissingIncludeError(lines.join("\n"));
    for (const line of lines) console.warn(`sync-scad:${line}`);
  }

  fs.mkdirSync(WEB_PUBLIC, { recursive: true });
  fs.writeFileSync(path.join(WEB_PUBLIC, "scad-bundle.json"), JSON.stringify({ files, assets }));
  const cat = catalogue();
  const thumbnails = syncThumbnails(cat.parts ?? []);
  fs.writeFileSync(path.join(WEB_PUBLIC, "catalogue.json"), JSON.stringify(cat));
  fs.writeFileSync(path.join(WEB_PUBLIC, "global-defaults.json"), JSON.stringify(globalConstants()));

  return { files: Object.keys(files).length, assets: Object.keys(assets).length, thumbnails };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);
if (isMain) {
  // SYNC_SCAD_ALLOW_MISSING=1 is the escape hatch for working on the web
  // app without the vendored submodules: the bundle is written anyway
  // and only the parts that need them fail, in the browser.
  const allowMissing = process.env.SYNC_SCAD_ALLOW_MISSING === "1";
  try {
    const { files, assets, thumbnails } = syncScad({ strict: !allowMissing });
    console.log(
      `sync-scad: bundled ${files} .scad files and ${assets} binary asset(s), wrote catalogue.json ` +
        `and ${thumbnails} part thumbnail(s)`,
    );
  } catch (error) {
    if (!(error instanceof MissingIncludeError)) throw error;
    console.error(
      `sync-scad: included files are missing, so parts that need them could not render:\n${error.message}\n` +
        "Run `git submodule update --init --recursive` to check out the vendored libraries, " +
        "or set SYNC_SCAD_ALLOW_MISSING=1 to write the bundle anyway.",
    );
    process.exit(1);
  }
}
